class OracleDatabase:
    def __init__(self, dsn: str, user: str, password: str):
        self.dsn, self.user, self.password = dsn, user, password

    @contextmanager
    def transaction(self) -> Iterator[object]:
        if oracledb is None:
            raise RuntimeError("python-oracledb is not installed")
        con = oracledb.connect(user=self.user, password=self.password, dsn=self.dsn)
        try:
            yield con
            con.commit()
        except BaseException:
            con.rollback()
            raise
        finally:
            con.close()

    def bootstrap(self) -> None:
        """Create every table, constraint, and index; safely repeatable on Oracle."""
        with self.transaction() as con:
            cur = con.cursor()
            for ddl in SCHEMA:
                try:
                    cur.execute(ddl)
                except oracledb.DatabaseError as exc:
                    # ORA-00955 covers an already-created table or index.
                    if getattr(exc.args[0], "code", None) != 955:
                        raise
            cur.close()


def database_from_environment() -> OracleDatabase:
    return OracleDatabase(
        os.getenv("ORACLE_DSN", "localhost:1521/FREEPDB1"),
        os.getenv("ORACLE_USER", "eventforge"),
        os.getenv("ORACLE_PASSWORD", ""),
    )
